# ========== 3. 分层颜色配置 ==========
# 说明：
#   'mode' 有两种：
#       'direct'   = 直接分层（按分数从高到低切层,不平行）
#       'parallel' = 平行分层（支持在任意位置做平行分班）
#
#   'config' 是分层方案,语法见下：
#
# ── 模式1: direct（直接分层）──
#   只给每层的人数,剩余的人作为最后一层：
#       'config': [42, 40, 32]
#       含义：A层42人、B层40人、C层32人,剩下的人自动作为D层
#
# ── 模式2: parallel（平行分层）──
#   语法1（简单）：全部直接分层,剩余平行分 parallel_groups 层
#       'config': [42, 40, 32]
#       'parallel_groups': 2
#       含义：A层42人、B层40人、C层32人,剩下的人平行分2层
#
#   语法2（元组）：中间某段平行分班
#       'config': [42, (40, 2), 32]
#       含义：A层42人、中间40人平行分2层、C层32人,剩余平行分 parallel_groups 层
#
#   语法3（列表）：同元组语法,只是用列表
#       'config': [42, [40, 2], 32]
#
#   语法4（字典）：更明确的写法
#       'config': [42, {'count': 40, 'groups': 2}, 32]
#
#   多个中间段平行分层：
#       'config': [(30, 2), 50, (20, 3)]
#       含义：前30人平行分2层、中间50人直接分层、后20人平行分3层
#       剩余的人平行分 parallel_groups 层
#
#   说明：
#       - (人数, 层数) 或 [人数, 层数] 表示该段人数平行分这么多层
#       - 纯数字 表示该段直接分层（切一层）
#       - 剩余学生始终平行分 parallel_groups 层（除非在 config 里显式安排完）
#       - 平行分班的逻辑：按加权平均排序后,按 mod (2*层数) 的方式"蛇形"轮流分配
#         目的是让平行班之间的总分尽量均衡

